#!/usr/bin/env node

const { writeFile } = require('node:fs/promises');
const path = require('node:path');

const SOURCE_URL = 'https://raw.githubusercontent.com/qwd/LocationList/master/China-City-List-latest.csv';
const TARGET_FILE = path.join(process.cwd(), 'lib', 'qweatherLocations.generated.ts');

function parseCsvLine(line) {
  const cells = [];
  let current = '';
  let quoted = false;

  for (let i = 0; i < line.length; i += 1) {
    const char = line[i];
    const next = line[i + 1];

    if (char === '"' && quoted && next === '"') {
      current += '"';
      i += 1;
    } else if (char === '"') {
      quoted = !quoted;
    } else if (char === ',' && !quoted) {
      cells.push(current);
      current = '';
    } else {
      current += char;
    }
  }

  cells.push(current);
  return cells;
}

function cleanName(value) {
  return String(value ?? '').trim();
}

async function main() {
  const response = await fetch(SOURCE_URL);
  if (!response.ok) {
    throw new Error(`Failed to download QWeather location list: HTTP ${response.status}`);
  }

  const csv = await response.text();
  const lines = csv.split(/\r?\n/).filter(Boolean);
  const version = lines[0]?.split(',')[0]?.trim() || 'China-City-List';
  const rows = lines.slice(2).map(parseCsvLine);

  const provinces = new Map();

  for (const row of rows) {
    const id = cleanName(row[0]);
    const districtName = cleanName(row[2]);
    const provinceName = cleanName(row[7]);
    const cityName = cleanName(row[9]);
    const adCode = cleanName(row[13]);

    if (!id || !districtName || !provinceName || !cityName) continue;

    if (!provinces.has(provinceName)) {
      provinces.set(provinceName, new Map());
    }

    const cities = provinces.get(provinceName);
    if (!cities.has(cityName)) {
      cities.set(cityName, []);
    }

    const items = cities.get(cityName);
    if (!items.some(item => item.id === id)) {
      items.push({ name: districtName, id, adCode });
    }
  }

  const data = [...provinces.entries()].map(([provinceName, cities]) => ({
    name: provinceName,
    cities: [...cities.entries()].map(([cityName, items]) => ({
      name: cityName,
      items: items.sort((a, b) => a.name.localeCompare(b.name, 'zh-CN')),
    })),
  }));

  const content = [
    '/* eslint-disable */',
    '// Generated by scripts/sync-qweather-locations.js.',
    `// Source: ${SOURCE_URL}`,
    '',
    'export type QWeatherLocationItem = { name: string; id: string; adCode: string };',
    'export type QWeatherLocationCity = { name: string; items: QWeatherLocationItem[] };',
    'export type QWeatherLocationProvince = { name: string; cities: QWeatherLocationCity[] };',
    '',
    `export const QWEATHER_LOCATION_VERSION = ${JSON.stringify(version)};`,
    `export const QWEATHER_LOCATION_SOURCE = ${JSON.stringify('https://github.com/qwd/LocationList')};`,
    `export const QWEATHER_LOCATION_GROUPS: QWeatherLocationProvince[] = ${JSON.stringify(data, null, 2)};`,
    '',
  ].join('\n');

  await writeFile(TARGET_FILE, content, 'utf8');
  const itemCount = data.reduce(
    (sum, province) => sum + province.cities.reduce((citySum, city) => citySum + city.items.length, 0),
    0,
  );
  console.log(`Wrote ${TARGET_FILE}`);
  console.log(`${version}: ${data.length} provinces, ${itemCount} locations`);
}

main().catch(error => {
  console.error(error);
  process.exit(1);
});
