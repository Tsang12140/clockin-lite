#!/usr/bin/env node

const { writeFile } = require('node:fs/promises');
const path = require('node:path');

const TARGET_FILE = path.join(process.cwd(), 'seed-demo.sql');

// 4 名演示员工，分属 3 个岗位（车缝 / 包装 / 质检）
const employees = [
  { name: '林芳',   gender: 'female', position: '车缝', hireDate: '2023-03-06', rate: 22.5 },
  { name: '陈秀英', gender: 'female', position: '包装', hireDate: '2022-11-14', rate: 20.0 },
  { name: '李慧明', gender: 'female', position: '质检', hireDate: '2024-02-20', rate: 23.0 },
  { name: '苏月琴', gender: 'female', position: '车缝', hireDate: '2023-07-12', rate: 21.5 },
];

const positionRates = {
  '车缝': 22.5,
  '包装': 19.5,
  '质检': 22.0,
};

function sqlString(value) {
  if (value == null) return 'NULL';
  return `'${String(value).replace(/'/g, "''")}'`;
}

function money(value) {
  return value.toFixed(2);
}

function dateParts(date) {
  return {
    year:  date.getFullYear(),
    month: date.getMonth() + 1,
    day:   date.getDate(),
    dow:   date.getDay(),
  };
}

function formatDate(date) {
  const { year, month, day } = dateParts(date);
  return `${year}-${String(month).padStart(2, '0')}-${String(day).padStart(2, '0')}`;
}

function addDays(date, days) {
  const next = new Date(date);
  next.setDate(next.getDate() + days);
  return next;
}

// 每天记录生成逻辑：主要 8-9 小时正常出勤，零星各类特殊情况
function recordFor(employee, employeeIndex, date) {
  const { month, day, dow } = dateParts(date);
  if (dow === 0) return { status: 'holiday', hours: null, label: null, note: null };

  const marker = (employeeIndex * 19 + month * 13 + day * 7) % 101;
  if (marker === 3)  return { status: 'leave',  hours: null,  label: null,   note: null };
  if (marker === 11) return { status: 'sick',   hours: null,  label: null,   note: null };
  if (marker === 29) return { status: 'absent', hours: null,  label: null,   note: null };
  if (marker === 47) return { status: 'custom', hours: null,  label: '培训', note: null };
  if (marker === 61) return { status: 'custom', hours: '4.0', label: '半天', note: null };

  // 正常出勤：工时在 8.0 / 8.5 / 9.0 之间循环，偶尔 9.5
  const steps = [8.0, 8.5, 9.0, 8.5, 8.0, 9.0, 8.5, 9.5, 8.0, 8.5];
  const hours = steps[(employeeIndex * 3 + day + month) % steps.length];
  return { status: 'worked', hours: hours.toFixed(1), label: null, note: null };
}

function values(rows) {
  return rows.map(row => `  (${row.join(', ')})`).join(',\n');
}

async function main() {
  const positionRows = Object.entries(positionRates)
    .map(([name, rate]) => [sqlString(name), sqlString(money(rate))]);

  const employeeRows = employees.map((employee, index) => [
    sqlString(employee.name),
    sqlString(employee.gender),
    sqlString(employee.position),
    sqlString(employee.hireDate),
    sqlString(money(employee.rate)),
    sqlString(`演示员工 ${index + 1}`),
  ]);

  const rateRows = employees.flatMap(employee => {
    const initialRate = employee.rate - 1;
    return [
      [sqlString(employee.name), sqlString(money(initialRate)), sqlString(employee.hireDate), sqlString('初始时薪')],
      [sqlString(employee.name), sqlString(money(employee.rate)), sqlString('2026-03-01'), sqlString('演示调薪')],
    ];
  });

  // 考勤范围：2026-01-01 至 2026-05-24（今年至昨天）
  const attendanceRows = [];
  for (let date = new Date(2026, 0, 1); date <= new Date(2026, 4, 24); date = addDays(date, 1)) {
    const workDate = formatDate(date);
    for (let index = 0; index < employees.length; index += 1) {
      const employee = employees[index];
      const record = recordFor(employee, index, date);
      attendanceRows.push([
        sqlString(employee.name),
        sqlString(workDate),
        record.hours == null ? 'NULL' : sqlString(record.hours),
        sqlString(record.status),
        sqlString(record.label),
        sqlString(record.note),
      ]);
    }
  }

  const content = `-- Demo seed for clockin-lite open-source setup.
-- Generated by scripts/generate-demo-seed.js.
-- Safe to re-run: it only deletes rows where is_demo = true.
-- Employees: 4 (车缝 2 / 包装 1 / 质检 1)
-- Attendance: 2026-01-01 to 2026-05-24

BEGIN;

ALTER TABLE clockin.employees
  ADD COLUMN IF NOT EXISTS is_demo BOOLEAN NOT NULL DEFAULT FALSE;
ALTER TABLE clockin.attendance_records
  ADD COLUMN IF NOT EXISTS is_demo BOOLEAN NOT NULL DEFAULT FALSE;
ALTER TABLE clockin.hourly_rate_history
  ADD COLUMN IF NOT EXISTS is_demo BOOLEAN NOT NULL DEFAULT FALSE;
ALTER TABLE clockin.holidays
  ADD COLUMN IF NOT EXISTS is_demo BOOLEAN NOT NULL DEFAULT FALSE;

DELETE FROM clockin.attendance_records WHERE is_demo = TRUE;
DELETE FROM clockin.hourly_rate_history WHERE is_demo = TRUE;
DELETE FROM clockin.employees WHERE is_demo = TRUE;

WITH seed_positions(name, default_rate) AS (
  VALUES
${values(positionRows)}
)
INSERT INTO clockin.positions (name, default_hourly_rate)
SELECT seed_positions.name, seed_positions.default_rate::numeric
FROM seed_positions
WHERE NOT EXISTS (
  SELECT 1 FROM clockin.positions WHERE positions.name = seed_positions.name
);

WITH demo_employees(name, gender, position_name, hire_date, hourly_rate, notes) AS (
  VALUES
${values(employeeRows)}
)
INSERT INTO clockin.employees (
  name, gender, position_id, status, hire_date, current_hourly_rate, notes, is_demo
)
SELECT
  demo_employees.name,
  demo_employees.gender,
  positions.id,
  'active',
  demo_employees.hire_date::date,
  demo_employees.hourly_rate::numeric,
  demo_employees.notes,
  TRUE
FROM demo_employees
LEFT JOIN clockin.positions ON positions.name = demo_employees.position_name;

WITH demo_rates(employee_name, rate, effective_date, notes) AS (
  VALUES
${values(rateRows)}
)
INSERT INTO clockin.hourly_rate_history (employee_id, rate, effective_date, notes, is_demo)
SELECT employees.id, demo_rates.rate::numeric, demo_rates.effective_date::date, demo_rates.notes, TRUE
FROM demo_rates
JOIN clockin.employees ON employees.name = demo_rates.employee_name AND employees.is_demo = TRUE;

WITH demo_records(employee_name, work_date, hours, status, status_label, note) AS (
  VALUES
${values(attendanceRows)}
)
INSERT INTO clockin.attendance_records (
  employee_id, work_date, hours, status, status_label, note, is_locked, is_demo
)
SELECT
  employees.id,
  demo_records.work_date::date,
  demo_records.hours::numeric,
  demo_records.status,
  demo_records.status_label,
  demo_records.note,
  TRUE,
  TRUE
FROM demo_records
JOIN clockin.employees ON employees.name = demo_records.employee_name AND employees.is_demo = TRUE;

COMMIT;
`;

  await writeFile(TARGET_FILE, content, 'utf8');
  console.log(`Wrote ${TARGET_FILE}`);
  console.log(`${employees.length} employees, ${rateRows.length} rate rows, ${attendanceRows.length} attendance rows`);
}

main().catch(error => {
  console.error(error);
  process.exit(1);
});

