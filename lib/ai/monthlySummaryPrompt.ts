type MonthlySummaryFacts = {
  year: number;
  month: number;
  current: unknown;
  previousMonth: unknown;
  lastYearSameMonth: unknown;
  yearToDate: unknown;
};

export function buildMonthlySummaryPrompt(facts: MonthlySummaryFacts) {
  return [
    '你是一个小微工厂考勤和工资助手。请根据提供的结构化考勤、工资、员工历史数据，生成一份给老板/文员看的月度工资总结。',
    '',
    '要求：',
    '1. 只根据输入数据分析，不要编造不存在的员工、金额、原因。',
    '2. 语言短、直白、务实，不使用复杂 HR 术语。',
    '3. 重点关注：',
    '   - 本月总工时、总工资、在职/离职员工参与情况',
    '   - 与上月相比，工资或工时明显增加/减少的员工',
    '   - 与去年同月相比，是否有明显变化',
    '   - 本年度内这个月是否偏高或偏低',
    '   - 请假、旷工、低工时、漏录、异常加班',
    '   - 离职员工是否仍有考勤或工资需要核对',
    '4. 不做法律判断，不评价企业制度是否合法。',
    '5. 如果数据不足，要明确说“数据不足，无法判断同比/环比”。',
    '6. 输出结构固定为：',
    '',
    '【本月概览】',
    '用 2-3 句话说明本月总工时、总工资、人数变化。',
    '',
    '【变化提醒】',
    '列出 1-5 条最值得注意的环比/同比变化。',
    '',
    '【异常关注】',
    '列出需要复核的员工和日期，说明原因。',
    '',
    '【发薪前建议】',
    '给出 2-3 条具体核对建议。',
    '',
    '输入数据：',
    JSON.stringify(facts),
  ].join('\n');
}
